import os
import joblib

from feature_engineering import build_feature_vector

# --------------------------------------------------
# Project paths
# --------------------------------------------------

BASE_DIR = os.path.dirname(
    os.path.dirname(
        os.path.abspath(__file__)
    )
)

CLASSIFIER_PATH = os.path.join(
    BASE_DIR,
    "models",
    "readiness_classifier.joblib"
)

REGRESSOR_PATH = os.path.join(
    BASE_DIR,
    "models",
    "readiness_regressor.joblib"
)

# --------------------------------------------------
# Load trained models
# --------------------------------------------------

classifier = joblib.load(CLASSIFIER_PATH)
regressor = joblib.load(REGRESSOR_PATH)

# --------------------------------------------------
# Predict readiness
# --------------------------------------------------

def predict_readiness(
    profile,
    resume_data=None,
    github_data=None,
    assessment_data=None,
    skill_profile=None
):
    """
    Predict student career readiness.

    skill_profile contains evidence-based skill
    scores generated by the skill-gap module.
    """
    features = build_feature_vector(
        profile=profile,
        resume_data=resume_data,
        github_data=github_data,
        assessment_data=assessment_data,
        skill_profile=skill_profile
    )

    category = classifier.predict(features)[0]
    score = regressor.predict(features)[0]
    score = max(0, min(100, float(score)))

    return {
        "readiness_category": category,
        "readiness_score": round(score, 2)
    }

